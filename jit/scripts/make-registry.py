#!/usr/bin/env python3
"""Generate the P4 agent profile registry.

The running xpost-agent loads its registry once at startup from XPOST_PROFILES
(or XPOST_ROOT/profiles.toml). The tracked profiles.toml has no entry for the
JIT containers, and the xpost repo must not be modified. This writes a private
registry the agent is restarted with:

- Every original fw/xdp entry is kept, but each build.command is replaced with
  a no-op so flash uses the exact prebuilt artifact already verified on the host
  (no rebuild touches the xpost repo at flash time).
- A jit_<prog> xdp entry is added per JIT container, artifact pointing at the
  worktree build/jit-elf/jit_<prog>.elf, linked fw just-drop-cag (just_xdp RX).
- AOT entries for div2/xdp_drop are added (the tracked registry does not
  profile them). case_mark/bitswap AOT already exist in the tracked registry
  and also link at the just_xdp slot 0x40380200, so they are reused as-is.

Usage: make-registry.py <xpost-root> <worktree> <out.toml>
"""
import re
import sys

root, worktree, out = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(f"{root}/profiles.toml").read()
text = re.sub(r'command = \[[^\]]*\]', 'command = ["true"]', text)

rx_fw = "just-drop-cag"
progs = ["div2", "xdp_drop", "case_mark", "just_drop", "just_tx", "firewall", "bitswap"]

lines = [text, "\n# --- P4 additions (generated by jit/scripts/make-registry.py) ---\n"]
for p in progs:
    lines.append(f"""
[[xdp]]
name = "jit_{p}"
fw = "{rx_fw}"
artifact = "{worktree}/build/jit-elf/jit_{p}.elf"
build = {{ cwd = ".", command = ["true"] }}
""")
# div2 and xdp_drop are not profiled in the tracked registry; case_mark and
# bitswap already are (their artifacts also link at 0x40380200), so adding them
# here would duplicate a name and fail the agent's registry validation.
for p in ["div2", "xdp_drop"]:
    lines.append(f"""
[[xdp]]
name = "{p}"
fw = "{rx_fw}"
artifact = "../build/{p}/{p}.elf"
build = {{ cwd = ".", command = ["true"] }}
""")
open(out, "w").write("".join(lines))
print(f"wrote {out}")