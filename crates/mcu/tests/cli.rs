use std::{fs, os::unix::fs::symlink, path::Path, process::Command};

fn mcu(action: &str, output: &Path) -> Command {
    let mut command = Command::new(env!("CARGO_BIN_EXE_mcu"));
    command.args([action, "--build-dir"]).arg(output);
    command
}

#[test]
fn unrelated_output_survives_even_with_a_generated_graph_header() {
    // A graph is reproducible input to Ninja, so it is not proof that other
    // files in the same directory are disposable.
    let scratch = tempfile::tempdir().unwrap();
    let output = scratch.path().join("existing user directory");
    fs::create_dir(&output).unwrap();
    let graph = b"# Generated by mcu. Run Ninja from the checkout root.\n";
    fs::write(output.join("build.ninja"), graph).unwrap();
    fs::write(output.join("notes.txt"), b"keep me").unwrap();
    let alias = scratch.path().join("alias");
    symlink(&output, &alias).unwrap();
    let subdir = output.join("nested");
    fs::create_dir(&subdir).unwrap();
    for path in [&output, &alias, &subdir.join("..")] {
        for action in ["clean", "build"] {
            let result = mcu(action, path).output().unwrap();
            assert!(
                !result.status.success()
                    && String::from_utf8_lossy(&result.stderr).contains("build directory"),
                "{action} {path:?}: {}",
                String::from_utf8_lossy(&result.stderr)
            );
            assert_eq!(fs::read(output.join("notes.txt")).unwrap(), b"keep me");
            assert_eq!(fs::read(output.join("build.ninja")).unwrap(), graph);
        }
    }
}

#[test]
fn cli_exposes_build_clean_and_doctor_only() {
    let binary = env!("CARGO_BIN_EXE_mcu");
    let output = Command::new(binary).arg("--help").output().unwrap();
    assert!(output.status.success());
    let help = String::from_utf8(output.stdout).unwrap();
    for name in ["build", "clean", "doctor"] {
        assert!(
            help.lines()
                .any(|row| row.split_whitespace().next() == Some(name))
        );
    }
    let removed = Command::new(binary).arg("test").output().unwrap();
    assert!(!removed.status.success());
    assert!(String::from_utf8_lossy(&removed.stderr).contains("unrecognized subcommand 'test'"));
}

#[test]
fn failed_build_can_retry_and_clean_only_its_output() {
    // An unavailable tool produces a failure before Ninja exists. The output
    // directory stays recoverable, while a copied marker grants no ownership.
    let scratch = tempfile::tempdir().unwrap();
    let output = scratch.path().join("owned output");
    let unrelated = scratch.path().join("unrelated output");
    fs::create_dir(&output).unwrap();
    for _ in 0..2 {
        let result = mcu("build", &output)
            .args(["--bpf-only", "-c", "just_drop"])
            .env("LIBBPF_MCU_CLANG", scratch.path().join("missing clang"))
            .output()
            .unwrap();
        assert!(!result.status.success());
        assert!(String::from_utf8_lossy(&result.stderr).contains("LIBBPF_MCU_CLANG"));
    }
    fs::create_dir(&unrelated).unwrap();
    fs::copy(output.join(".mcu-build"), unrelated.join(".mcu-build")).unwrap();
    fs::write(unrelated.join("notes.txt"), "keep").unwrap();
    assert!(!mcu("clean", &unrelated).status().unwrap().success());

    // A cache configured within a previously owned root stays protected.
    let cache = output.join("cargo target");
    fs::create_dir(&cache).unwrap();
    fs::write(cache.join("CACHEDIR.TAG"), "cache").unwrap();
    assert!(!mcu("clean", &output).status().unwrap().success());
    assert!(cache.join("CACHEDIR.TAG").is_file());
    fs::remove_dir_all(&cache).unwrap();

    assert!(mcu("clean", &output).status().unwrap().success());
    assert!(!output.exists());
    assert_eq!(
        fs::read_to_string(unrelated.join("notes.txt")).unwrap(),
        "keep"
    );
}
